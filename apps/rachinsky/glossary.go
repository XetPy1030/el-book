// Unit — старая мера: как называется, по каким словам её узнать в тексте задачи,
// к какой группе относится и чем помочь — соотношение со старыми мерами и современный
// эквивалент. Деньги (рубль, копейка) в словарь не входят: они и так понятны.
type Unit struct {
	Name  string // «Аршин»
	Group string // «Длина», «Вес», …
	// Stems — начала слов: токен в тексте, начинающийся с любого из них, считается этой мерой.
	Stems []string
	// Words — точные словоформы: для мер, у которых начало слова совпадает с другими словами
	// («мера» и «мерил»); токен засчитывается, только если равен одной из форм целиком.
	Words []string
	Note  string // «1 аршин = 16 вершков ≈ 71 см»
}


// unitsIn возвращает меры, встречающиеся в тексте задачи, в порядке словаря.
func unitsIn(text string) []Unit {
	toks := words(text)
	var out []Unit
	for _, u := range units {
		if u.matches(toks) {
			out = append(out, u)
		}
	}
	return out
}

func (u Unit) matches(toks []string) bool {
	for _, w := range toks {
		for _, s := range u.Stems {
			if strings.HasPrefix(w, s) {
				return true
			}
		}
		for _, exact := range u.Words {
			if w == exact {
				return true
			}
		}
	}
	return false
}

// words делит текст на слова из кириллических букв, приведённые к нижнему регистру.
func words(text string) []string {
	return strings.FieldsFunc(strings.ToLower(text), func(r rune) bool {
		return !(r >= 'а' && r <= 'я' || r == 'ё')
	})
}
